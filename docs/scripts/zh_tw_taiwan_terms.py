def apply_taiwan_terms(text: str) -> str:
    """按词长降序套用台湾用词。"""
    for src, dst in sorted(TW_TERM_PAIRS, key=lambda x: -len(x[0])):
        if src in text:
            text = text.replace(src, dst)
    return text
